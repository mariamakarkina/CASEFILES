function startInvestigation() {
    const params = new URLSearchParams(window.location.search);
    const caseId = params.get("id") || "1";

    window.location.href = `investigation.html?id=${caseId}`;
}

function renderCase() {
    const params = new URLSearchParams(window.location.search);
    const caseId = params.get("id") || "1";

    const currentCase = casesData[caseId];

    if (!currentCase) {
        document.querySelector("main").innerHTML = `
            <h1>Дело не найдено</h1>
            <p>Такого дела нет в архиве.</p>
            <a href="index.html">Вернуться на главную</a>
        `;
        return;
    }

    document.getElementById("case-number").textContent = currentCase.number;
    document.getElementById("case-title").textContent = currentCase.title;
    document.getElementById("case-category").textContent = currentCase.category;
    document.getElementById("case-date").textContent = currentCase.date;
    document.getElementById("case-status").textContent = currentCase.status;
    document.getElementById("case-brief").textContent = currentCase.description;

    document.getElementById("suspects-count").textContent =
        `${String(currentCase.suspects.length).padStart(2, "0")} фигуранта`;

    const suspectsList = document.getElementById("suspects-list");
    suspectsList.innerHTML = "";

    currentCase.suspects.forEach((suspect, index) => {
        const card = document.createElement("article");
        card.className = "suspect-card";

        card.innerHTML = `
            <div class="suspect-number">ПОДОЗРЕВАЕМЫЙ №${String(index + 1).padStart(2, "0")}</div>
            <h3>${suspect.name}</h3>
            <p class="suspect-role">${suspect.role}</p>
            <p class="suspect-description">${suspect.description}</p>
        `;

        suspectsList.appendChild(card);
    });
}

document.addEventListener("DOMContentLoaded", renderCase);
